import 'dotenv/config';
import EmbeddedPostgres from 'embedded-postgres';
import fs from 'node:fs';
import path from 'node:path';
const url=new URL(process.env.DATABASE_URL);
if (!['localhost','127.0.0.1'].includes(url.hostname)) throw new Error('Локальный запуск требует localhost в DATABASE_URL');
const databaseDir=path.resolve('../.local/postgres');
const pg=new EmbeddedPostgres({databaseDir,user:decodeURIComponent(url.username),password:decodeURIComponent(url.password),port:Number(url.port||5432),persistent:true,postgresFlags:['-h','127.0.0.1'],onLog:()=>{},onError:message=>console.error(String(message))});
if(!fs.existsSync(path.join(databaseDir,'PG_VERSION'))) await pg.initialise();
await pg.start();
const client=pg.getPgClient();await client.connect();
const name=url.pathname.slice(1);
if(!/^[a-zA-Z0-9_]+$/.test(name)) throw new Error('Некорректное имя базы');
if(!(await client.query('SELECT 1 FROM pg_database WHERE datname=$1',[name])).rowCount) await client.query(`CREATE DATABASE "${name}"`);
await client.end();console.log(`Локальный PostgreSQL готов на порту ${url.port}. Данные: .local/postgres`);
for(const signal of ['SIGTERM','SIGINT']) process.on(signal,async()=>{await pg.stop();process.exit(0);});
setInterval(()=>{},60000);
